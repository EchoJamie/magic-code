/**
 * 共享语言 · **自有进程的归属账**（U50）——「哪些进程是这一代运行起的」这一件事的落点。
 *
 * 出处：设计 · 会话与运行管理「本机执行结构」末句与「离开、停止与异常退出」那一行——
 *
 * > **工具**：由所属执行者创建和回收，本地子进程/进程组、MCP stdio 与 HTTP 连接
 * > 均可追溯到 Run。PID 和创建时间仅作诊断，用户按会话/工作操作。**非 Magic 创建的
 * > 外部服务不被停止动作误杀**。
 * >
 * > 执行者崩溃或被杀 ｜ 管理者收回独占权与**已登记自有进程组**，记录异常。
 *
 * 「任何存活进程都须有负责人」（同文档头一句）——执行者被 `SIGKILL` 时它自己来不及
 * 收尾，**谁起的那一组进程**就得有人知道。这一份账就是那个「有人知道」：起进程的那一方
 * 记一笔，管收尾的那一方照它收。
 *
 * ## 两条定死的规矩
 *
 * 1. **归属在启动那一刻定死**（`detached` ⇒ 自成进程组，组长 ＝ 子进程 pid）。此后按
 *    **组**收——不数进程树：数树有两处补不上的洞（父一崩 PPID 链就断；记下来的一串号
 *    到收尾时未必还是那几个），这两处已在 `@magic/mcp` 的传输层写过一次（见那份头注）。
 * 2. **身份不只是号**。号会被系统回收再分配（PID 重用），故一笔账记**两位**：
 *    `pgid` 与**组长自己的启动时刻**（`startedAt`，由 `ps` 读出来）。收尾之前两位都要
 *    对得上才算「还是当初那一组」——对不上**一个信号都不发**（误杀一个无关进程比漏收
 *    一个我们自己的进程坏得多）。
 *
 * ## 记账的边界
 *
 * 记的是**我们起的**那些：`exec` 跑出去的每一条命令（自成一组）、MCP 的每一条 stdio
 * 连接（自成一组）。HTTP 连接、用户自己起的服务、别人的进程**一个字都不进这本账**
 * ——「非 Magic 创建的外部服务不被停止动作误杀」在这一层是结构上的：不在账上的，
 * 收尾那一跳根本看不到它。
 *
 * ⚠️ **它不是运行事实**（`runs.ts` 那一份）：那份说「这条会话在跑什么、我该做什么」，
 * 会给窗口看；这一份说「这一代手上握着哪几个进程号」，**只在本机管理者与执行者之间走**
 * （进程号不上屏——设计：「不把 PID 常驻」）。
 */

/**
 * **一笔自有进程的账**——一个进程组，与它凭什么算是我们的。
 *
 * `startedAt` 缺省（`undefined`）＝ 那一刻读不到组长的启动时刻（`ps` 不可用 / 刚起还没
 * 落到进程表里）。**缺省不等于没问题**：核对的时候读不到就**不动它**（拿不准的不杀）。
 */
export type OwnedProcess = {
  /** 进程组 id（＝组长 pid，`detached` 保证）。 */
  readonly pgid: number
  /** 组长**自己**的启动时刻（毫秒）——身份核对的那一位；读不到就缺席。 */
  readonly startedAt: number | undefined
  /**
   * 这一组是**什么**起的——`exec` 那条命令 / `mcp:<服务器名>`。
   *
   * 它是**诊断与回执**用的：收尾时说不出来「收的是谁」，那句「没能收掉」就没人能查。
   * 用户按会话/工作操作，不按它。
   */
  readonly what: string
}

/**
 * **归属账**——起进程的那一方记一笔，管收尾的那一方照它收。
 *
 * 两个动作：`add` 记一笔（**读一次组长的身份**，把两位一起记下）、`list` 要一份现在
 * 还活着的。
 *
 * ⚠️ **`list` 是活的**（顺手把已经没了的摘掉）：账随进程生死走，不是一本越记越长的册子
 * ——一场会话里跑几百条命令是常事，账却只该有「此刻还站着的那几个」。
 */
export interface ProcessLedger {
  /**
   * 记一笔——`pgid` ＝ 刚 spawn 出来的那个进程组，`what` ＝ 谁起的。
   *
   * 读取组长的启动时刻是**记账的一部分**（不是可选的锦上添花）：这一位缺了，收尾那一跳
   * 就证明不了归属，只能不动它。故实现要在**组长还在的时候**读它——那一刻就在眼前。
   */
  add(input: { readonly pgid: number; readonly what: string }): void
  /** 此刻还活着的那些（顺手摘掉已经没了的）。 */
  list(): readonly OwnedProcess[]
  /**
   * **账变了**（记了一笔）——上报那一侧据此**当场**说一声。
   *
   * 为什么要有它：账是**别人替你收**的判据，晚一步报就等于「那一段窗口里起的进程没人
   * 认领」。等下一次汇报（用例里那种定时重报）来不及——一条 `exec` 起完到被杀之间可能
   * 只有几百毫秒。摘掉那一边不必报：上报那一侧每次都要现读 `list()`，它自己看得到。
   */
  onChange(listener: () => void): void
}
