/**
 * 控制面消息预算——**产生侧与传输层共用的同一条线**。
 *
 * 由来（2026-11-21 接续事故）：连接层原先只有一个「发送欠账 8 MiB」的保护，它管的是
 * 「对端不读时服务端最多替它攒多少」。产生侧却可以合法地造一条 13 MB 的
 * `session.state`（目录摘要带了工具结果全文），于是保护机制把「单条消息太大」
 * 误判成「对端不读」，静默 `terminate()`——用户只看到「连不上引擎」。
 *
 * 两个数分开：
 * - `WIRE_MESSAGE_BUDGET_BYTES`：**单条消息**不得超过它。产生侧据此分批/裁剪；
 *   传输层据此把「单条超限」与「积压」分开报，并在断开前留下可诊断的原因。
 * - `WIRE_SEND_BACKLOG_BYTES`：**尚未送出的欠账**不得超过它。这是给「对端不读」
 *   的内存保护，与单条消息的大小无关。
 *
 * 两者同值只是当前实现的选择——语义不同，别再把它们当同一个门槛用。
 */
export const WIRE_MESSAGE_BUDGET_BYTES = 8 * 1024 * 1024

/** 发送欠账上限——对端不读时，服务端最多替它攒这么多（见上）。 */
export const WIRE_SEND_BACKLOG_BYTES = 8 * 1024 * 1024
