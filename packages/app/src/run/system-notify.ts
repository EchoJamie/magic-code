/**
 * **本机系统通知**（U50 · U98 重定）——设计那一句里的「**无人连接时**可使用本机系统通知」。
 *
 * 三条口径：
 * - **只在那一个时刻用**：**没有窗口正看着这条会话**的时候（U86 起三类同此）——有人看着，
 *   屏上那一行就是通知，弹第二份是复述；而「A 页开着、B 出的事」按这条尺子**是没人看着**
 *   （连着不算），故它照弹（D38 那半）；
 * - **它只是提醒，不是结果**：设计明文「**权限未授予不影响持久结果**」——这一跳发不出去，
 *   未读那一份**照旧在盘上**，下一次打开照样汇总。故这里**一律不抛、不重试**；
 * - **一句话，不带会话 id**：管理者认不得标题（目录在窗口那一头），而把一个内部 id 弹到
 *   用户桌面上是最该避免的那种「实现细节漏出去」。故弹的是**类别 ＋ 指路**，
 *   具体是哪一条由用户打开 Magic 之后那张汇总说（那时外壳手上有标题）。
 *
 * ## ⚠️ 今天**一处都不接**（U98）——缺省是「不发」
 *
 * 这一支原先有一份实现：**借系统的脚本解释器**发出去（起一个子进程，跑一行
 * `display notification`）。2026-09-26 **删掉**了，因为它借的是**别人的身份**——
 * macOS 把那条通知算在 **Script Editor** 头上：用户点「显示」，系统开的是那个应用，
 * 而不是出事的那条会话（**用户在自己机器上撞到并报了回来**）。
 *
 * **那不是哪个参数写错了，是那条路本身借了别人的身份。** 所以是**删**，不是「留着不接」：
 * 留着一条已知坏了的路，下一个人会把它再接上——**「指一个跑不了的入口，比不指更坏」**。
 *
 * 缺省因此就是**什么都不做的** `silentNotifier`：**接一个真通知器从此是显式动作**——
 * 端口（`SystemNotifier` ＋ `ManagerOptions.notifySystem`）照旧留着，语义变成
 * **「谁要发谁自己接」**。
 *
 * ⚠️ **今天「没看着 ⇒ 本机系统通知」那一格空着，这是有意的**（不是漏做）：它等
 * **菜单栏 app 给出身份**（bundle id——通知归它、点击回它、再由它落到那条会话）之后，
 * 接上**对的那一支**。
 */

/** 发一条系统通知——**发不出去就算了**（见文件头注）。 */
export type SystemNotifier = (text: string) => void

/**
 * **缺省那一支：一个字都不发**（U98）——**今天谁都不接**，故这就是缺省。
 *
 * 它在场是为了让「谁要发谁自己接」落在**一个说不出发的缺省**上：没有它，管理者那一边
 * 就只能要么缺省等于「真发」（U98 前的旧局面），要么把这一格做成可选（那会让
 * 「没人接」与「接了个空的」在调用点分不开）。
 *
 * 它**一次调用都不做**，故谁也不需要为它准备什么（不需要授权、不需要平台、不会失败）。
 */
export const silentNotifier: SystemNotifier = () => {}
