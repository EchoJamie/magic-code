/**
 * 参数取用 —— 工具执行体的入口一件。
 *
 * 模型的参数是**外部输入**（`Readonly<Record<string, unknown>>`）：键名与类型都不是我们能
 * 假定的。三条口径：
 * - **错键名不被猜中**——只认契约锚定的键（技术方案 · 工具 · 参数键），不搞候选键兜底：
 *   猜中一次，模型的错就被记住一次；
 * - **缺席 ≠ 空串**——可选键没给＝取缺省（路径缺省＝工作区默认根）；给了空串是**错**，
 *   因为「空路径」不是任何一处工作区；
 * - **判定只此一处**——`isText` 是类型谓词：收窄交给 tsc，报文交给各工具（键名不同、
 *   说法不同）。
 */

/** 非空字符串？——参数取用的唯一判据（字符串且**去掉空白后**不空）。 */
export function isText(value: unknown): value is string {
  return typeof value === 'string' && value.trim() !== ''
}
