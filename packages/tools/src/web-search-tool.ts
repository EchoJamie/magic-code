/**
 * `web_search` —— **联网搜索：定义留下，不注册**（U88）。
 *
 * 出处：设计 · 网页与搜索「两件工具」表的第二行（回执形状见其「**搜索的回执长什么样
 * （2026-09-26 实测）**」那一节）。
 *
 * ## 这一单做到哪儿为止（⚠️ 本文件的性质）
 *
 * 用户 2026-09-26 定：「magic 里**先留下工具、契约等信息，先不注册到实际工具中**。」
 * 由头两条：一条是**回执形状刚从四次真调用里实测定下来**——**先钉住，免得它烂掉**；
 * 一条是**搜索源还没定**（规划侧主张 Tavily，用户未表态）⇒ **接线等源定了再做**。
 *
 * ⇒ 这个文件里**只有「这件工具长什么样」**——名字 · 一句话说明 · 参数（`WEB_SEARCH_SPEC`）：
 *
 * - **没有执行体**（`run` 这一格压根不在）⇒ 它**跑不起来**，而且是**结构上**跑不起来：
 *   没有谁拿着它去执行，也没有**任何搜索源**接着（不发网络请求 · 不读 key · 不加配置格）；
 * - **也不注册**：不在 `toolset.ts` 的默认七件里，装配那一处（`assembly.ts` 的追加集）
 *   也**不构造它** ⇒ **模型看不见它**。用例另有一条咬这个：
 *   `test/web-search-tool.test.ts`（域内）与 `app/test/web-search-absent.test.ts`
 *   （整条真装配，看发出去的那份请求的 `tools`）。
 *
 * ## 回执成形为什么不在这个文件里
 *
 * 成形出来的那根字符串是**主模型读到的东西**，由那台**独立小服务**（`WebSearchService`）
 * 在出结果之前走一遍——而服务将来落哪一域还没定（设计：「进程内的一层组件，还是真起一个
 * 进程」待定），**域之间又不互相 import**。放这儿，服务那一侧就够不着。故它落在**契约**里：
 * `@magic/contracts` 的 `searchReceiptOf`——「一处定、两处用」，与 `web.ts` 的
 * `webTargetOf` 同一条姿势。
 *
 * ## 名字为什么是 `web_search`
 *
 * 设计明写：工具名是**技术级**、落实施时定，只给了一条硬约束——**要与既有的 `grep`
 * 分得开**。`grep` 搜的是**工作区里的文件内容**（沙箱那一条底），这一件搜的是**网上**；
 * `web_search` 又与既有的 `web_fetch` 同一族（一个找、一个取），一眼分得开。
 * ——这就是那条约束的落地。
 */

import type { ToolSpec } from '@magic/contracts'

/**
 * 参数模式——**只有 `query` 一把键**。
 *
 * ## 参照面里的另两把（`allowed_domains` / `blocked_domains`）为什么不要
 *
 * 参照面是 `{query, allowed_domains?, blocked_domains?}`，工单把「我们要哪几个」留给设计定。
 * **设计里没有域过滤这一件事**：「两件工具」表、实测那一节的回执形状（抬头 / 链接段 / 正文）、
 * 「已定的取舍」六条——一个字都没提过按域收窄。而它**偏偏不是白拿的**：
 *
 * - **回执里没有一处回述域过滤**（形状是逐字钉住的）⇒ 一次带过滤的搜索与不带过滤的，
 *   回执**长得一模一样**，模型看不出自己收窄过——那正是「没问到 ≠ 没有」那类错误的前身；
 * - 域过滤是**源那一侧的话术**（如 Tavily 的 `include_domains`），而**源还没定**——
 *   现在把它写进键名，等于先替未定的源选好了词。
 *
 * ⇒ **先只留 `query`**。这是**纯追加**的一件事：将来要加，加两个可选键、改这一处即可
 * （回执形状一个字不用动）；反过来，把已经发出去的键收回来是**断契约**——故宁可先少不敢多。
 *
 * ## `description` 按「注册那天要能用」写
 *
 * 它是**给模型读的说明书**（送模型的那一份），故照 `web_fetch` 那一条的分寸写全：
 * **这一件做什么** · **它回的是什么** · **什么时候不要用它**（要某一页的原文走 `web_fetch`，
 * 不要把这一件当取原文的路——它回的是综合过的东西，拿它要原文只会怪它不全）。
 */
export const WEB_SEARCH_PARAMETERS = {
  type: 'object',
  description:
    '联网搜索：给一句话，这一趟自己跑查询、读若干页，回**综合后的答案与出处**。' +
    '它回的是综合过的东西、不是某一页的原文——要原文用 web_fetch 取那一页。',
  properties: {
    query: {
      type: 'string',
      description: '要查什么——就是你要知道的那件事',
    },
  },
  required: ['query'],
  additionalProperties: false,
} as const

/**
 * 这件工具的规格——**名字 · 一句话说明 · 参数 · 危险归类**（`ToolSpec` 那四件）。
 *
 * ⚠️ **危险归类声明的是方向**（外发 ⇒ 必闸）——与 `web_fetch` 同一条口径（设计 ·
 * 网页与搜索「已定的取舍」：「取网是外发 ⇒ 必闸」）。
 *
 * ⚠️ **判定不在本单，也不在这一格**（设计 · 工具执行与权限：「危险归类**只声明不判定**」）：
 * 权限域的机械分析表（`analyze.ts`）里**还没有 `web_search` 这一格**。它今天走不到那儿
 * （**没注册**）；真接线那一步要连同那一格一起做——卡上要说清**发往哪个域名**（搜索后端
 * 那个），以及「总是允许」按什么给。**今天缺那一格也不等于放行**：分析表覆盖不到的形态
 * 一律兜底最重的一档（`unclassifiable`），照旧必闸——错的只会是「嫌它问得多」，不是
 * 「悄悄放过去」。
 *
 * ⚠️ **`summary` 一句话说明**：与 `web_fetch` 的 `取网页（取回 → 按问题提炼 → 只回答案）`
 * 同一形——括号里那半句说清「它内部干了什么」，因为这一件与取网页最容易混
 * （两件都「省上下文」，但一个找、一个取）。
 */
export const WEB_SEARCH_SPEC: ToolSpec = {
  name: 'web_search',
  summary: '联网搜索（一次查询 → 读若干页 → 回答案与出处）',
  parameters: WEB_SEARCH_PARAMETERS,
  danger: { level: 'gated', reason: 'outbound' },
}
