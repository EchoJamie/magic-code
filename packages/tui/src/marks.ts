/**
 * **记号**（U112）——屏上用得着的那些单字符，**一处出处**。
 *
 * 出处：设计 · 终端交互「符号 ＋ 动效：一套」与「取字准则与逐条取舍」。
 * 2026-10-01 用户裁定之后**扩过白名单、换过一个字形**（见下）——这一份是裁定后的终态。
 *
 * ## 一条骨架
 *
 * **记号只出现在两处——行首（身份）与行尾（状态）**；行首身份**主要靠缩进**
 * （你/助手顶格 · 工具与结果缩进一级 · 卡片 `│`），记号只标**需要区分的少数行**。
 *
 * ## 字形白名单（裁定后 · 十三个）
 *
 * `›` `▸` `·` `⋯` `│` `●` `○` `◆` `▲` `■` `✓` `×` `!`
 *
 * 四条取字准则：① **宽度稳**（窄）；② ⛔ 不用带 emoji 变体的码位（`⏺`U+23FA 实测
 * 在 macOS 上回落到 **Apple Color Emoji**，会画成彩色双宽）；③ ⛔ **覆盖差的新码位不用**
 * （`⟳`U+27F3 不在 Menlo；**`◉`U+25C9 在 SF Mono 与 Monaco 上都没有**——它因此被换掉）；
 * ④ **无色也分得开**：身份靠**形状＋缩进**，颜色只承担轻重。
 *
 * ⚠️ **白名单是「准则推出来的」，不是「照着当时那几个位置抄的」**（2026-10-01 用户纠正）：
 * 按准则（老码位 ＋ 无 emoji 变体 ＋ 窄），`○`(U+25CB) · `▲`(U+25B2) · `■`(U+25A0) ·
 * `!`(U+0021) **都合格**，故一并收进白名单。**但收进来的每一个都得有自己那一格语义位**
 * ——见下面那张表：**不许随手用**（同一个形在两处说两件事，就是记号体系没定）。
 */

/**
 * 字形白名单——**十三个**（上面那张准则推出来的清单，次序照「身份 → 状态」摆）。
 *
 * 导出是为了让判据**锚在它上面**：屏上出现白名单以外的记号，用例会红。
 */
export const GLYPH_WHITELIST: readonly string[] = [
  // —— 行首 · 身份（五）——
  '›',
  '▸',
  '·',
  '⋯',
  '│',
  // —— 状态那一格 · 六个状态各一个形（六）——
  '●',
  '○',
  '◆',
  '▲',
  '■',
  // —— 行尾 · 三种收梢（三）——
  '✓',
  '×',
  '!',
]

/**
 * 屏上用的记号——**一处出处**（改一处，全屏跟着改）。
 *
 * ## 每一个的**语义位**（不许随手用）
 *
 * | 记号 | 额定的那件事 | 出现在哪 |
 * | --- | --- | --- |
 * | `you` `tool` | **这是谁说的 / 这是动手** | 行首身份 |
 * | `receipt` `thinking` `card` | **回执 / 思考 / 卡片** | 行首身份 |
 * | `dot` `idle` `ring` `error` `unknown` | **状态的六个形**（进行中 / 空闲 / 要你定夺 / 出错 / 待确认） | 状态那一格 |
 * | `ok` `fail` `warn` | **收梢三态**（成 / 败 / 没跑成） | 工具行**行尾** |
 *
 * ⚠️ **`●` 是唯一跨两处的**（状态格「工作中」＋ 工具行行尾「跑动中」），那不是随手用：
 * 两处说的是**同一件事**（这一件**正在进行**），design 那张表把它们列在同一列
 * （「进行中（动）」）里。**别的形一格一位，不跨。**
 */
export const MARKS = {
  /** 你的交代——`›`（窄、老码位、覆盖好、轻）。 */
  you: '›',
  /** 工具调用行的身份——`▸`（`⟳` 的语义是刷新/循环，用在「一次调用」上错了）。 */
  tool: '▸',
  /** 系统回执——`·`（老码位、轻）。**也是状态行的分栏点**（最弱色，只是分栏，不是内容）。 */
  receipt: '·',
  /** 思考段（窄窗那一档）——`⋯`。 */
  thinking: '⋯',
  /** 卡片左边框——`│`（box-drawing，全覆盖）。 */
  card: '│',

  /** 状态格 · **进行中**（工作中 / 正在重试）——`●`。也是工具行行尾「跑动中」那一位。 */
  dot: '●',
  /** 状态格 · **空闲**（手上没活）——`○`。 */
  idle: '○',
  /**
   * 状态格 · **要你定夺**——`◆`（U+25C6）。
   *
   * ⚠️ **2026-10-01 用户裁定：由 `◉`(U+25C9) 换成它**。由头是取字准则③：
   * `◉` **在 SF Mono 与 Monaco 上都没有**（本机实测：两个 `cmap` 里都没有它）——
   * 换一台把终端字体设成 SF Mono 的机器，那一位就回落别的字、宽度与基线都飘。
   * `◆` 是老码位、覆盖好，**形状与 `●` 明显不同**（菱形 vs 圆点），语义也贴
   * 「要你定夺」那件事（需要你拍一下）。
   */
  ring: '◆',
  /** 状态格 · **出错**——`▲`。 */
  error: '▲',
  /** 状态格 · **状态待确认**（失联——那一格是**放弃判断**，不是「快看我」）——`■`。 */
  unknown: '■',

  /** 行尾 · **成**——`✓`。 */
  ok: '✓',
  /** 行尾 · **败**——`×`（U+00D7；不是 `✘`，那个有 emoji 风险，`×` 最稳最轻）。 */
  fail: '×',
  /**
   * 行尾 · **没跑成（要你再看一眼）**——`!`（U+0021）。
   *
   * 归这两档：**规约扣下 / 材料超限停批**（压根没跑，但也不是失败）与
   * **已停止 · 结果未确认**（那一代核销了，这一笔的结果不会再来）。
   * ASCII，宽度恒 1，无 emoji 变体。
   */
  warn: '!',
} as const

/** 记号的取值。 */
export type MarkName = keyof typeof MARKS
