/**
 * **记号**（U112）——屏上用得着的那些单字符，**一处出处**。
 *
 * 出处：设计 · 终端交互「符号 ＋ 动效：一套」与「取字准则与逐条取舍」。
 *
 * ## 一条骨架
 *
 * **记号只出现在两处——行首（身份）与行尾（状态）**；行首身份**主要靠缩进**
 * （你/助手顶格 · 工具与结果缩进一级 · 卡片 `│`），记号只标**需要区分的少数行**。
 *
 * ## 字形白名单（设计原文，逐字）
 *
 * `›` `▸` `·` `⋯` `│` `●` `◉` `✓` `×`。**禁用**：带 emoji 变体的码位、新符号块的码位。
 *
 * 四条取字准则（前三已实测）：① **宽度稳**；② ⛔ 不用带 emoji 变体的码位（`⏺`U+23FA ·
 * `●`U+25CF · `⚙`U+2699 · `✘`U+2718 都实测有渲染成彩色双宽的风险）；③ ⛔ 不用等宽字体
 * 覆盖差的新码位（`⟳`U+27F3 · `⏺`U+23FA 回落别的字体，宽度与基线都飘）；④ **无色也分得开**：
 * 身份靠**形状＋缩进**，颜色只承担轻重。
 *
 * ## ⚠️ 两处如实记在案
 *
 * - **`●` 留在白名单里**（设计自己留的）：它虽然带 emoji 变体风险，但「状态是一颗圆点」
 *   这件事本单不翻案——设计那一行写的是「圆点没问题；问题是同形只靠颜色分」。
 * - **`○` `▲` `■` 不在白名单的字面上，本单照用**（空闲 · 出错 · 状态待确认三态）。
 *   三条由头：它们与 `●` **同属几何形状块**（同样的老码位、同样的 emoji 属性 —— 拿 `●`
 *   的风险尺子去量它们，量出来是同一个数）；设计那一节**只重定了工作/等你这两种状态**
 *   （表里那两行给的正是 `●` 与 `◉`），没有要改另外三态的字；而**白名单之外一律不用**
 *   这句若连它们一起禁，那三态就**没有字可用**了（白名单里只剩 `·` 与 `⋯`，两个都与
 *   「回执」「思考」撞语义）。⇒ 白名单读作「**本单选出并保留的字形表**」，
 *   而这三个是**改动之前就在用的**，不在本单的改动面上。**这一条已写进回报，供裁**。
 */

/** 字形白名单——**设计原文那九个**（顺序照设计）。 */
export const GLYPH_WHITELIST: readonly string[] = ['›', '▸', '·', '⋯', '│', '●', '◉', '✓', '×']

