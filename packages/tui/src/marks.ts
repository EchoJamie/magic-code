/**
 * **记号**（U112）——屏上用得着的那些单字符，**一处出处**。
 *
 * 出处：设计 · 终端交互「符号 ＋ 动效：一套」与「取字准则与逐条取舍」。
 * 2026-10-01 用户裁定之后**扩过白名单、换过一个字形**（见下）——这一份是裁定后的终态。
 *
 * ## 一条骨架
 *
 * **记号只出现在两处——行首（身份）与行尾（状态）**；行首身份**主要靠缩进**
 * （你/助手顶格 · 工具与结果缩进一级 · 卡片 `│`），记号只标**需要区分的少数行**。
 *
 * ## 字形白名单（裁定后 · 十三个）
 *
 * `›` `▸` `·` `⋯` `│` `●` `○` `◊` `▲` `■` `✓` `×` `!`
 *
 * 四条取字准则：① **宽度稳**（窄）；② ⛔ 不用带 emoji 变体的码位（`⏺`U+23FA 实测
 * 在 macOS 上回落到 **Apple Color Emoji**，会画成彩色双宽）；③ ⛔ **覆盖差的新码位不用**
 * （`⟳`U+27F3 不在 Menlo；**`◉`U+25C9 在 SF Mono 与 Monaco 上都没有**——它因此被换掉）；
 * ④ **无色也分得开**：身份靠**形状＋缩进**，颜色只承担轻重。
 *
 * ⚠️ **白名单是「准则推出来的」，不是「照着当时那几个位置抄的」**（2026-10-01 用户纠正）：
 * 按准则（老码位 ＋ 无 emoji 变体 ＋ 窄），`○`(U+25CB) · `▲`(U+25B2) · `■`(U+25A0) ·
 * `!`(U+0021) **都合格**，故一并收进白名单。**但收进来的每一个都得有自己那一格语义位**
 * ——见下面那张表：**不许随手用**（同一个形在两处说两件事，就是记号体系没定）。
 */

/**
 * 字形白名单——**十三个**（上面那张准则推出来的清单，次序照「身份 → 状态」摆）。
 *
 * 导出是为了让判据**锚在它上面**：屏上出现白名单以外的记号，用例会红。
 */
