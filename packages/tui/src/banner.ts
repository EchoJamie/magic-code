/**
 * 启动字标（品牌视觉 · TUI Banner）——**记录区最前面那一块**，启动印一次。
 *
 * 出处：vault `品牌视觉/TUI Banner 设计.md` ＋ 同目录 `资源/折跃-v1/tui/` 的三份文本资源。
 * **规格以设计文档为准**；本文件只做两件事：把文本资源**一字不改**地落进仓库，
 * 以及按文档的宽度规则选版。
 *
 * ## 为什么内联成常量，而不是随包带 .txt 去读
 *
 * 三条，都是这个仓库自己的账：
 * - **启动路径不添一笔 I/O**——`cli.ts` 连 `@magic/tui` 的 import 都刻意推迟到起外壳那一步
 *   （Ink ＋ React 实测 120.4ms，见那儿「一帧都不画的路不付这笔账」那条注），
 *   启动路径上每一笔都是明账。读文件还多出两件要处理的事：「路径相对谁」
 *   （打包 / 安装之后 `import.meta.dir` 未必是源码目录）与读失败的回退——
 *   而这份内容是**死的**，一笔 I/O 换不来什么。
 * - **`createShell` 是同步的**（构造即订阅，见 `shell.ts`）——异步读盘会把这条线劈开，
 *   而字标**必须**在**第一帧**就位（它就是「启动时印一次」那句话）。
 * - **它是显示常量，与 `PALETTE` 同族**——色板也是内联的（`components/lines.ts`）。
 *
 * ## 三份资源
 *
 * | 常量 | 资源 | 画幅 | 什么时候印 |
 * | --- | --- | --- | --- |
 * | `BANNER_WIDE` | `magic-code-wide.txt` | 53 列 × 5 行 | 窗口 **≥ 57 列**（**缺省就用它**） |
 * | `BANNER_COMPACT` | `magic-code-compact.txt` | 10 列 | 窄于 57 列、仍放得下 **12 列**（10 ＋ 左留白 2） |
 * | `BANNER_ASCII` | `magic-code-ascii.txt` | 53 列 × 5 行 | **留着，先不自动切**（见下） |
 *
 * ⚠️ **块字符不自动检测**（规划侧已定）：**终端不告诉你字体信息**——装没装块字符的字体，
 * 从 `TERM` / 环境变量 / 任何终端查询上都看不出来，**检测必错**。故**默认就用块字版**。
 * ASCII 那份作为资源留在仓库里（它是「字体不支持块字符」时唯一还能呈现**完整产品名**的一份），
 * 但此刻**没有任何宽度会切到它**——日后若要开关，那是一个**配置面**的事，另议。
 *
 * ⚠️ **行尾补白照抄**：资源是 53 列定宽，末三行的行尾有补白空格（字形本身如此）。
 * 抄下来才与「53 列 × 5 行」对得上，也才与设计文档的核对结果对得上。
 * 帧上它们会被归一化（`test/screen.ts` 的 `plain` 抹行尾），不影响布局判据。
 */

