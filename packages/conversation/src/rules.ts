/**
 * 规约送达 —— **什么时候把哪几条送进上下文**（U32 · 对话域这一半）。
 *
 * 上游是执行域的 `ProjectRules`（有什么、在哪儿、是哪一版）；本文件持有的是**会话内**的
 * 两样记账，加上「工具产生副作用之前」这道闸：
 *
 * - **作用域**（`scope`）——本会话**接触过的**目标路径，累积、去重、**有界**（先进先出）。
 *   会话开局是空的（只取各根一级），每碰一处就长一点。用途是决定**送哪些**（近目录约定
 *   只细化其子树）。**它有界只影响「历史」那一截**——本批的正确性不靠它（见下 `pinned`）。
 * - **最近一次请求送达了什么**（`deliveredNow`）——**判据是「最近那次真实模型请求里有没有
 *   它」，不是「历史上送过没有」**（2026-09-20 裁，改了首轮的口径）。账上记的是**那一趟
 *   实际送出去的材料本身**（来源 · 范围 · 正文），比对就是逐字比——**没有版本号、没有摘要**
 *   （2026-09-21 裁：材料不做版本管理，见契约 `ProjectRule`）。
 *
 * ## 为什么由对话域持有这两样
 *
 * 「这一轮在动哪儿」只有主循环知道（它拿到的是模型的工具调用），而「送进上下文」也只有它
 * 能做（上下文由条目与系统提示词装配，那是本域的事）。执行域只管读盘，它不该知道谁在跑。
 *
 * ## 送达发生在两处（顺序即语义）
 *
 * 1. **每次模型调用之前**（`promptFor`）——把**当前作用域 ＋ 被拦批钉住的目标**适用的规约
 *    接进系统提示词，并把这一趟真正送出去的材料**整个替换**进 `deliveredNow`。
 *    这是「无路径规则首次模型调用前载入」与「条件规则在目标相关时送达」共同的落点。
 * 2. **一批工具执行之前**（`preflight`）——拿**这一批全部**的目标查一遍：**有没送达过的新内容
 *    就拦下整批**（回填「需重审」，见 `needsReviewText`），并把这批的目标**钉住**
 *    （`pinned`），保证下一次重审请求**一定带上它们**。
 *    **第一次副作用因此没有发生**——拦在 `invoke` 之前，沙箱与闸门都还没被碰到。
 *    **材料没读完整则独立停批**（`overflow`，2026-09-20 二轮裁；四轮把触发扩到「发现面
 *    没看成」）：那与「有没有新内容」是两件事——没进来的那几份**不在 `documents` 里**，
 *    所以「没新内容」推不出「送齐了」。
 *
 * 拦截**只在新材料上发生**：同一份材料还在最近那次请求里就照常执行，模型重提的那一次因此
 * 只会执行一次（「重审后仅执行一次」）。
 *
 * ## 判据为什么是「最近一次请求」（2026-09-20 裁）
 *
 * 首轮用的是「进过至少一次请求的材料，永久记账」。它错在一个**静默**上：规约正文**只在
 * 系统提示词里**（进不了条目流、历史里没有它），而作用域有界——同一个目标被后来的目标挤出去
 * 之后，那份材料就**不在当前请求里了**，可账上还记着「已送达」，于是**写下去了**。
 * 「送达」是一件**当下**的事（这次请求里有没有），不是一件**曾经**的事。
 *
 * 代价如实记：规则正文在 system、不在历史 ⇒ **恢复 / 切回一条会话时会被再送一次**
 * （新实例的账是空的）。那是**必要行为**，不是白付——不重送，模型手上就真没有那份规约。
 * **不为省下这一趟而把域内账公开给装配**（那要把 `RulesDelivery` 提到公开面，是契约改形）。
 */

import type { ProjectRule, ProjectRules, ToolCall } from '@magic/contracts'
import { withProjectRules } from './prompt/rules.ts'

/**
 * 被拦下来那一批的**去处**——拦了就得有个交代，三种情形各自说清（见 `needsReviewText`）。
 *
 * 三选一而不是一个布尔：三件事对模型的要求**完全不同**——
 * 前两种是「等下一趟、照新规约重提」，第三种是「**别再提了**，去告诉用户」。
 */
export type PreflightResult =
  | { readonly kind: 'pass' }
  /** 有没送达过的新规约——这批一份都不执行，材料已钉住、下一次请求必带。 */
  | { readonly kind: 'review'; readonly blocking: readonly ProjectRule[] }
  /**
   * **材料没读完整，这一批停在这儿**（2026-09-20 裁）——回来的那份**不是全的**，
   * 故「目标上的规约都送到了」这句话**不能成立**。既不静默执行（可能带着没读到的规约就动手），
   * 也不无限重试（没照诊断处置之前，再提多少次还是读不全）——明说，并把人指到该动的地方。
   *
   * 触发**不止一种**（2026-09-20 四轮裁把判据说全）：加载器到上限（份数 / 总量）、
   * **发现面没看成**（目录读不动 · 层级到顶）。`truncated` 一个位管全部；**具体是哪一种
   * 由来源诊断说**，回执只报「没读完」这个事实（见 `overflowText`）。
   */
  | { readonly kind: 'overflow' }

/**
 * 一次会话的规约送达。
 *
 * 有状态、**按会话各一份**（装配在 `createConversationSession` 里造）——切了会话就是另
 * 一本账：那一头碰过哪些目录、最近送过哪几版，与这一头无关。
 */
export type RulesDelivery = {
  /** 一次模型调用前：把当前作用域（＋被钉住的目标）的规约接上，并替换「最近送达」那一本账。 */
  readonly promptFor: (base: string) => string
  /**
   * 一批工具执行前：这一批能不能动手。
   *
   * **查的是这一批的全部目标**（不是被历史缓存裁过的那些——见 `pinned` 与 `MAX_SCOPE_TARGETS`）。
   */
  readonly preflight: (calls: readonly ToolCall[]) => PreflightResult
}

/**
 * **历史**作用域的条数上限——**先进先出**。
 *
 * 「不要递归把整仓规约都塞进每次调用」这条纪律，靠两道拦：一道是**只送碰过的**
 * （此处的累积），另一道是**送过的不能无限攒**（这个数）。一个长会话在仓库里挪上几百个
 * 文件之后，早年的目标既不再相关、又每趟都要重新走一遍祖先目录——留着就是纯成本。
 *
 * ⚠️ **它只管历史那一截**（2026-09-20 裁）：上限之外的东西**不是「丢了」**，而是
 * 「不再自动跟着走」——回头再碰那个目录，它照旧被收回来、那几份规约照旧在下一趟请求里。
 * **本批的正确性不靠它**：本批的目标**先查、后收**（`preflight` 查的就是本批的全部目标），
 * 且被拦批的目标会被**钉住**（`pinned`），不受这个上限裁剪。
 */
export const MAX_SCOPE_TARGETS = 64

/** 造一份送达账（一条会话一份）。 */
export function createRulesDelivery(rules: ProjectRules): RulesDelivery {
  /** 本会话接触过的目标（累积、去重、按接触序）——**历史**，有界。 */
  const scope: string[] = []
  /** 去重面——与 `scope` 同生共死（出队时一并删）。 */
  const known = new Set<string>()
  /**
   * **被拦批钉住的目标**——下一次请求**必须**带上它们（2026-09-20 裁）。
   *
   * 由头：被拦的那一批要能在下一次请求里看到新规约，才谈得上「照新规约复核后重提」。
   * 而下一个目标集是从历史作用域算出来的——**同一个上限会把它再裁一遍**：拦了、送了
   * 一趟、又裁掉、再拦……那是一个**死循环**，而模型永远看不到那份规约。
   * 钉住的就是这条循环的出口：**拦下的那一批自己带的材料，下一个请求一份不少**。
   *
   * 它由下一次「放行」清掉（那时这批已经执行过，历史那条路自会照 `scope` 走）。
   */
  let pinned: string[] = []
  /**
   * **最近一次真实模型请求里送达的材料本身**——`preflight` 的判据。
   *
   * 记的就是那一趟递上去的那几条（`ProjectRule` 的字段原样），比的时候逐字比
   * （见 `sameMaterial`）——**不另造材料身份**：不算摘要、不编号、不存历史版本
   * （2026-09-21 裁，见契约 `ProjectRule`）。多占的内存就是那几份正文，而它们本来就在
   * 这一趟的请求里，条数与总量同受加载器那几道上限约束。
   *
   * `promptFor` 每趟**整个替换**它（先清后填）：这样「挤出去过又回来的」那份会被如实
   * 判成「没送到」，而不是被一个永久的账本蒙混过去（见文件头注「判据为什么是最近一次请求」）。
   */
  let deliveredNow: readonly ProjectRule[] = []

  const absorb = (fresh: readonly string[]): void => {
    for (const target of fresh) {
      if (known.has(target)) continue
      known.add(target)
      scope.push(target)
    }

    while (scope.length > MAX_SCOPE_TARGETS) {
      const dropped = scope.shift()
      if (dropped !== undefined) known.delete(dropped)
    }
  }

  /** 这一趟请求要带上的目标——**钉住的在前**（它们不受历史上限裁剪）。 */
  const requestedTargets = (): readonly string[] => [
    ...pinned,
    ...scope.filter((target) => !pinned.includes(target)),
  ]

  return {
    promptFor: (base: string): string => {
      const load = rules.load(requestedTargets())
      // **先清后填**——这本账说的是「最近这一次请求里有什么」，不是「历来送过什么」。
      // 填进去的就是**马上要递上去的那一份材料**（同一个 `load` 的产物，不是另算的一串号）。
      deliveredNow = load.documents

      return withProjectRules(base, load)
    },

    preflight: (calls: readonly ToolCall[]): PreflightResult => {
      const batch = calls.flatMap(targetsOf)
      // **查这一批的全部目标**（＋这一趟请求带的那一拨），不先裁再查：
      // 先裁再查＝「这一批里被裁掉的那几个目标」的规约压根没人看（首轮实测：同批 65 次写、
      // 第一个目标有规约，全部写成功、任何请求都没收到那份规约）。
      const load = rules.load([...requestedTargets(), ...batch])

      // **没读完整先判，且单独判**（2026-09-20 二轮裁；四轮把触发说全）——`truncated` 说的是
      // 「**回来那份不是全的**」，而没进来的那几份**压根不在 `documents` 里**，故「blocking 为空」
      // **推不出**「目标上的规约都送到了」：挡住的恰恰可能是新目标上的新规约。
      // 触发不只有上限——**发现面没看成**（目录读不动 · 层级到顶）同样置这一位，一样停批。
      //
      // 首轮把它套在 `blocking.length > 0` 里，于是**越接近上限越漏**：64 份小规则都在首个请求
      // 送达、第 65 份 `guard/AGENTS.md` 被截掉 ⇒ blocking 空 ⇒ 直接放行，实测
      // `written=true / guardInAnySystem=false`——那份约束**一次都没送到，写却发生了**。
      // 判据因此**不依赖「已返回的文档里有新内容」**：完整性是这一趟自己的事。
      if (load.truncated) {
        // 照样钉住：这一批的目标材料（能装下的那些）下一趟仍要在，诊断处置好之后重提才有得看
        pin(batch)
        // 「回填说『已送入上下文』」在这种情形是假话（那份可能压根没进来）⇒ **停在这一批**，
        // 不再靠重提（没照诊断处置之前，再提多少次也还是读不全）。
        return { kind: 'overflow' }
      }

      // 没新目标也照查一遍：**规约可能刚被改过**（改过的正文＝另一份材料＝该重送一次）。
      // 这一趟是幂等的——同一份材料还在最近那次请求里就什么都不返回，故不产生多余的拦截。
      const blocking = load.documents.filter(
        (document) => !deliveredNow.some((delivered) => sameMaterial(delivered, document)),
      )

      if (blocking.length > 0) {
        // 拦下了：**把这批的目标钉住**——下一次请求一定带上它们的规约，循环由此闭合
        pin(batch)
        return { kind: 'review', blocking }
      }

      // 放行——这一批的历史使命到此为止：钉住的目标并进历史作用域，钉子的活干完了
      unpin()
      absorb(batch)
      return { kind: 'pass' }
    },
  }

  /**
   * 钉住这一批的目标——**只增不减**（同一批里多个目标指向同一处时去重）。
   *
   * 并进 `pinned` 而不是替换：上一个钉子还没解（模型没照那份规约重提就换了别的目标）
   * 时，那份材料**照旧得在**——它是模型手上唯一见过的那一版。
   */
  function pin(batch: readonly string[]): void {
    pinned = [...new Set([...pinned, ...batch])]
  }

  /** 解钉——并进历史作用域（**由有界的那一半接管**，此后按常规的进出走）。 */
  function unpin(): void {
    absorb(pinned)
    pinned = []
  }
}

/**
 * 一次工具调用**静态可推**的目标路径。
 *
 * 工具集 v1 的参数键是**契约冻结**的（`ports.ts` · 参数键全表）：`read` / `write` / `edit`
 * 按 `path`；`grep` / `glob` / `ls` 的 `path` 可选（缺省＝默认根——那一层在会话开局就送达了，
 * 故缺席不必另补）。键名不带方言，取不到就该没有。
 *
 * ⚠️ **`exec` 不在其列，这是有意为之的限度**：它只收 `cmd`，而任意 shell 字符串实际会碰
 * 哪些文件**静态推不出来**（`cd src && ./build.sh` 就是现成的反例）。故它的范围按**执行 cwd**
 * （＝工作区默认根）算——那几条根一级的规约在会话开局就已经在上下文里了。
 * **不假装推得出来**，是本版对这件事的诚实处置（设计 · 项目规约第 4 条明写）。
 */
function targetsOf(call: ToolCall): readonly string[] {
  const path = call.args['path']
  return typeof path === 'string' && path.trim() !== '' ? [path] : []
}

/**
 * 两条规约是不是**同一份材料**——逐字比**实际送出去的那几样**：
 * 来源（`kind` / `path` / `name`）· 作用域（`root` / `scope`）· 生效条件（`paths`）· 正文（`text`）。
 * 这是 `preflight` 「新不新」的**唯一判据**，与 `deliveredNow` 里存的那份材料对着比。
 *
 * **不能只比正文**（2026-09-21 裁，也是这条判据唯一一件不能省的事）：材料里**范围是它的一部分**
 * ——同一套约定按目录铺开（根 `AGENTS.md` 与 `src/AGENTS.md` 写着同一段话，复制粘贴起手、
 * 脚本生成、模板铺开都很常见）是**两份材料**，各管一摊。只比正文的话，送过根那份就等于说
 * 子目录那份也送过了 ⇒ 它**永远不送、也不拦**——「副作用之前送到」在最需要它的场景里静默失效。
 * 条件同理：同一份正文把 `src/**` 改成 `lib/**`，送出去的适用面就变了，那是另一份材料
 * （`text` 里**没有**这一段——正文是摘掉 front-matter 的那一段）。
 *
 * 为什么是**逐字比**而不是算个号（2026-09-21 用户明裁）：材料不做版本管理——没有内容 hash、
 * 没有版本号，也不许换个名字（`materialKey` / `signature` 之类）把同一套机制藏起来。
 * 手上本来就有最近那趟**真实送出去的材料**，直接比它最准，也少一处能悄悄失准的合成。
 */
function sameMaterial(left: ProjectRule, right: ProjectRule): boolean {
  return (
    left.kind === right.kind &&
    left.path === right.path &&
    left.name === right.name &&
    left.root === right.root &&
    left.scope === right.scope &&
    left.text === right.text &&
    left.paths.length === right.paths.length &&
    left.paths.every((pattern, index) => pattern === right.paths[index])
  )
}

/**
 * 「没跑」那两句话的**首行**——屏上那一格照抄它（2026-09-20 二轮裁）。
 *
 * 首行是那行工具在屏上的**整句话**（`verdictOf` 只取首行），故这一行得自己读出「没跑」来。
 * ⚠️ 这是**给人看的**要求，不是判据：说「这一笔没跑」的是结果上那一位 `notExecuted`
 * （三轮裁——此前外壳按这行字认，见 `agent-loop.ts` · `withholds`）。改字不改状态。
 *
 * 后头的正文照旧给模型说全三件（没执行 · 为什么 · 接下来怎么办），不是给人看的摘要。
 */
const UNEXECUTED_REVIEW = '未执行 · 规约已更新，重新审视后再操作'
/**
 * 没读完那一句（**措辞由本单定**，规划侧只点了重审那一句）——**说的是事实，不是对谁的命令**。
 *
 * 为什么不用「先别重提」：那句话是**对模型说的**（回填正文里就有），而这一格**用户也在读**，
 * 「重提」是谁的动作在那行字里看不出来。事实句两种读者都读得通；「该谁动」由正文那句
 * 「请把这件事告诉用户，让他先看那份诊断」交代。
 *
 * ⚠️ **不报「太多」**（2026-09-20 四轮裁）：停批的触发**不止与「多」有关的那两种**
 * （目录读不动 · 层级太深 · 份数或总量到顶 · 五轮又收进「点名的补充来源没归位成功」），
 * 后几种与「多」无关——旧句「规约太多，一次装不下」放在不可读那一屏上就是一句失准的话。
 * 这一格只报**没读完整**这个事实，**是哪一种由来源诊断说**（见 `overflowText`）。
 */
const UNEXECUTED_OVERFLOW = '未执行 · 项目规约未完整读取'

/**
 * 被拦下那一次调用的回填文本——**说清三件**：没执行 · 为什么 · 接下来怎么办。
 *
 * 不这么写，模型会以为工具坏了（或者以为写完了）；而这一批**确实一次都没执行**，
 * 回填必须让「重提一次」成为显然的下一步。
 */
export function needsReviewText(blocking: readonly ProjectRule[]): string {
  const names = blocking.map((rule) => rule.name).join(' · ')

  return (
    `${UNEXECUTED_REVIEW}\n` +
    `这个目标上刚发现新的项目规约（${names}），已送入上下文——` +
    `请照新规约复核这次调用，然后重新提出；这一次没有任何副作用发生。`
  )
}

/**
 * 没读完那一次的回填文本（`PreflightResult.overflow`）——**说清三件**，但**下一步不一样**。
 *
 * 「已送入上下文」在这儿是**假话**（材料压根没全进来），所以换一套：说清**没执行**、
 * **为什么**（规约没读完整）、以及**该谁动**（用户，不是模型自己重提）。
 * **明写「不要重提」**：没照诊断处置之前，重提一百次也还是读不全，那只会白烧往返——
 * 这正是工单说的「不静默执行或无限重试」。
 *
 * **原因不在这儿编**（2026-09-20 四轮裁；五轮把「点名的补充来源没归位成功」也收进这一族）：
 * 触发有几种（目录读不动 · 层级太深 · 份数或总量到顶 · 点名的来源没读到），**是哪种、在哪一处，
 * 由来源诊断给**（`problems`，用户跑 `magic --check` 看得到）。旧正文把它们都写成「多到装不下」
 * ——不可读与层级太深那两屏上，那是一句失准的话；而**为此各造一套回执**又是多出来的第二套说法。
 * 故只报「没读完」，把原因指回诊断那一处——那句括注只是**列举可能**，不是判据。
 */
export function overflowText(): string {
  return (
    `${UNEXECUTED_OVERFLOW}\n` +
    `这个项目里的规约这一趟没能完整读完（哪一处、为什么，见 magic --check 那份诊断——` +
    `目录没看成 · 层级太深 · 份数或总量到顶 · 点名的来源没读到，都可能）。` +
    `没法保证目标上的规约都送到，所以这次没有任何副作用发生；` +
    `不要重提这一批——先照那份诊断把那一处处置好，然后再说。` +
    `请把这件事告诉用户，让他先看那份诊断。`
  )
}
